namespace Win32Emu.VirtualFileSystem
{
	/// <summary>
	/// CD track types
	/// </summary>
	public enum CdTrackType
	{
		/// <summary>
		/// Audio track (CD-DA)
		/// </summary>
		Audio,
	
		/// <summary>
		/// Mode 1 data track
		/// </summary>
		Mode1,
	
		/// <summary>
		/// Mode 1 data track (raw)
		/// </summary>
		Mode1Raw,
	
		/// <summary>
		/// Mode 2 data track
		/// </summary>
		Mode2,
	
		/// <summary>
		/// Mode 2 formless data track
		/// </summary>
		Mode2Formless,
	
		/// <summary>
		/// Mode 2 Form 1 data track
		/// </summary>
		Mode2Form1,
	
		/// <summary>
		/// Mode 2 Form 2 data track
		/// </summary>
		Mode2Form2,
	
		/// <summary>
		/// Mode 2 data track (raw)
		/// </summary>
		Mode2Raw
	}
}